import type { FastifyPluginAsync } from 'fastify';
import type { GameNewsDto } from '@streets/shared';
import { RoundService } from '../services/round.service.js';

const roundInfoRoutes: FastifyPluginAsync = async (fastify) => {
  /** 0.1.0-E: global announcements plus posts for the current round. */
  fastify.get('/current/news', async () => {
    const round = await RoundService.getCurrent(fastify.prisma);
    if (!round) return { news: [] as GameNewsDto[] };

    const rows = await fastify.prisma.gameNews.findMany({
      where: {
        publishedAt: { lte: new Date() },
        OR: [{ roundId: null }, { roundId: round.id }],
      },
      include: { createdBy: { select: { username: true } } },
      orderBy: [{ isPinned: 'desc' }, { publishedAt: 'desc' }],
      take: 50,
    });

    // 2.0.0. Link Daily stories back to their city's turf board.
    const eventIds = [...new Set(rows.map((row) => row.cityMemoryEventId).filter((id): id is string => Boolean(id)))];
    const slugByEventId = new Map<string, string>();
    if (eventIds.length) {
      const events = await fastify.prisma.cityMemoryEvent.findMany({
        where: { id: { in: eventIds } },
        select: { id: true, city: { select: { slug: true } } },
      });
      for (const event of events) slugByEventId.set(event.id, event.city.slug);
    }

    const news: GameNewsDto[] = rows.map((row) => ({
      id: row.id,
      title: row.title,
      body: row.body,
      isPinned: row.isPinned,
      publishedAt: row.publishedAt.toISOString(),
      authorName: row.createdBy?.username ?? null,
      autoGenerated: row.autoGenerated,
      citySlug: row.cityMemoryEventId ? slugByEventId.get(row.cityMemoryEventId) ?? null : null,
    }));

    return { news };
  });
};

export default roundInfoRoutes;
