import { randomInt } from 'node:crypto';
import { Prisma, type PrismaClient } from '@prisma/client';
import type { Db } from '../utils/db.js';

const DAY_MS = 24 * 60 * 60 * 1000;

function utcDate(year: number, month: number, day: number): Date {
  return new Date(Date.UTC(year, month, day));
}

function monthKey(date: Date): string {
  return `${date.getUTCFullYear()}-${String(date.getUTCMonth() + 1).padStart(2, '0')}`;
}

/** Fridays whose whole Friday-to-Monday window belongs to the requested month. */
export function candidateWeekendStarts(year: number, month: number): Date[] {
  const days = new Date(Date.UTC(year, month + 1, 0)).getUTCDate();
  const candidates: Date[] = [];
  for (let day = 1; day <= days - 3; day += 1) {
    const start = utcDate(year, month, day);
    if (start.getUTCDay() === 5) candidates.push(start);
  }
  return candidates;
}

export function chooseWeekendStart(year: number, month: number, random = randomInt): Date {
  const candidates = candidateWeekendStarts(year, month);
  return candidates[random(candidates.length)]!;
}

export function doubleXpWeekendActive(
  weekend: { startsAt: Date; endsAt: Date } | null | undefined,
  now = new Date(),
): boolean {
  return Boolean(weekend && weekend.startsAt <= now && weekend.endsAt > now);
}

function announcementTitle(start: Date): string {
  return `🔥 Double XP Weekend · ${start.toLocaleDateString('en-US', { month: 'long', day: 'numeric', timeZone: 'UTC' })}`;
}

function announcementBody(start: Date, end: Date): string {
  const first = start.toLocaleDateString('en-US', { weekday: 'long', month: 'long', day: 'numeric', timeZone: 'UTC' });
  const last = new Date(end.getTime() - DAY_MS).toLocaleDateString('en-US', { weekday: 'long', month: 'long', day: 'numeric', timeZone: 'UTC' });
  return `The streets are paying double from **${first}** through **${last}**.\n\nEarn **2× profile XP** and **2× Street Pass Cred** on every eligible earn during the weekend. The bonus ends Monday at 00:00 UTC.`;
}

async function ensureMonth(prisma: PrismaClient, year: number, month: number, now: Date): Promise<void> {
  const key = `${year}-${String(month + 1).padStart(2, '0')}`;
  const existing = await prisma.doubleXpWeekend.findUnique({ where: { monthKey: key } });
  if (existing) return;

  const startsAt = chooseWeekendStart(year, month);
  const endsAt = new Date(startsAt.getTime() + 3 * DAY_MS);
  const announceAt = new Date(startsAt.getTime() - 4 * DAY_MS);
  try {
    await prisma.$transaction(async (tx) => {
      const claimed = await tx.doubleXpWeekend.create({ data: { monthKey: key, startsAt, endsAt, announceAt } });
      const news = await tx.gameNews.create({
        data: {
          title: announcementTitle(startsAt),
          body: announcementBody(startsAt, endsAt),
          publishedAt: announceAt > now ? announceAt : now,
          broadcast: true,
          autoGenerated: true,
        },
      });
      await tx.doubleXpWeekend.update({ where: { id: claimed.id }, data: { newsId: news.id } });
    });
  } catch (error) {
    // Two app instances can initialize the same month at once. The unique month
    // key makes one authoritative; the losing transaction is safe to ignore.
    if (!(error instanceof Prisma.PrismaClientKnownRequestError) || error.code !== 'P2002') throw error;
  }
}

export const DoubleXpWeekendService = {
  async isActive(db: Db | PrismaClient, now = new Date()): Promise<boolean> {
    const weekend = await db.doubleXpWeekend.findFirst({
      where: { startsAt: { lte: now }, endsAt: { gt: now } },
      select: { startsAt: true, endsAt: true },
    });
    return doubleXpWeekendActive(weekend, now);
  },

  /** Ensure this month and next month exist, including their scheduled news post. */
  async sweep(prisma: PrismaClient, now = new Date()): Promise<{ created: number }> {
    const currentMonth = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 1));
    const nextMonth = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() + 1, 1));
    let created = 0;
    for (const target of [currentMonth, nextMonth]) {
      const before = await prisma.doubleXpWeekend.count({ where: { monthKey: monthKey(target) } });
      await ensureMonth(prisma, target.getUTCFullYear(), target.getUTCMonth(), now);
      created += before === 0 ? 1 : 0;
    }
    return { created };
  },
};
