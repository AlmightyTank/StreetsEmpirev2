import { markdownToPlainText } from '@streets/shared';
import type { Db } from '../utils/db.js';
import { ActivityService } from './activity.service.js';

/**
 * 2.0.0 empire-story-2-0. Streets Daily: public CityMemoryEvents become held
 * GameNews drafts (far-future publishedAt = the existing scheduled-post flow).
 * Admins edit, publishNow, or delete them; players never see a draft.
 */

const GENERATOR_RUN_CAP = 20;
/** Drafts sit this far ahead until an admin publishes or rejects them. */
export const DRAFT_HELD_MS = 10 * 365 * 24 * 60 * 60_000;

interface MemoryEventLike {
  id: string;
  roundId: string;
  cityId: string;
  kind: string;
  actors: unknown;
  summary: unknown;
  happenedAt: Date;
}

function summaryOf(event: MemoryEventLike): Record<string, unknown> {
  const summary = (event as { summary?: unknown }).summary;
  return summary && typeof summary === 'object' && !Array.isArray(summary)
    ? summary as Record<string, unknown>
    : {};
}

function text(value: unknown): string | null {
  return typeof value === 'string' && value.length ? value : null;
}

export function buildDailyDraft(event: MemoryEventLike, cityName: string): { title: string; body: string } | null {
  const summary = summaryOf(event);
  switch (event.kind) {
    case 'takeover': {
      const next = text(summary.nextAllianceId) ?? 'a new crew';
      const blocks = typeof summary.nextBlocksHeld === 'number' ? ` holding ${summary.nextBlocksHeld} blocks` : '';
      return {
        title: `🏙️ ${cityName} under new control`,
        body: `Word on the street: **${next}** runs ${cityName} now${blocks}.\n\nEverybody adjusts. Nobody forgets.`,
      };
    }
    case 'war_win': {
      const district = text(summary.district);
      const reason = text(summary.reason)?.toLowerCase() ?? 'settled';
      return {
        title: `🔥 Block war ${reason}${district ? ` in ${district}` : ''}`,
        body: `A block war over **${district ?? 'the block'}** ended by **${reason}**.\n\nWinner takes the corner. Loser takes notes.`,
      };
    }
    case 'business_flip': {
      return {
        title: `💼 New management on the block`,
        body: `A business changed hands in **${cityName}**.\n\nRegisters ring different tonight.`,
      };
    }
    case 'crackdown': {
      return {
        title: `🚔 Feds sweep ${cityName}`,
        body: `A federal crackdown swept **${cityName}**.\n\nKeep your head down and your corners covered.`,
      };
    }
    case 'operation_complete': {
      return {
        title: `🌙 Something went down in ${cityName}`,
        body: `A criminal operation played out in **${cityName}**.\n\nDetails are thin. Reputations are not.`,
      };
    }
    default:
      return null;
  }
}

export async function generateDailyDrafts(db: Db, input: { roundId: string; limit?: number }): Promise<number> {
  const events = await db.cityMemoryEvent.findMany({
    where: { roundId: input.roundId, visibility: 'public' },
    orderBy: { happenedAt: 'asc' },
    take: Math.min(Math.max(input.limit ?? GENERATOR_RUN_CAP, 1), 100),
  }) as MemoryEventLike[];
  if (!events.length) return 0;
  const covered = await db.gameNews.findMany({
    where: { roundId: input.roundId, cityMemoryEventId: { in: events.map((event) => event.id) } },
    select: { cityMemoryEventId: true },
  });
  const coveredIds = new Set(covered.map((row) => row.cityMemoryEventId));
  const fresh = events.filter((event) => !coveredIds.has(event.id));
  if (!fresh.length) return 0;
  const cities = await db.city.findMany({
    where: { id: { in: [...new Set(fresh.map((event) => event.cityId))] } },
    select: { id: true, name: true },
  });
  const nameByCityId = new Map(cities.map((city) => [city.id, city.name]));
  const heldAt = new Date(Date.now() + DRAFT_HELD_MS);
  let created = 0;
  for (const event of fresh) {
    const draft = buildDailyDraft(event, nameByCityId.get(event.cityId) ?? 'the city');
    if (!draft) continue;
    await db.gameNews.create({
      data: {
        roundId: event.roundId,
        title: draft.title,
        body: draft.body,
        publishedAt: heldAt,
        autoGenerated: true,
        cityMemoryEventId: event.id,
      },
    });
    created += 1;
  }
  return created;
}

function actorIds(event: { actors: unknown }): string[] {
  return Array.isArray(event.actors) ? event.actors.filter((id): id is string => typeof id === 'string') : [];
}

/**
 * Street Report: when an admin publishes an auto-draft, everyone named in the
 * memory event gets a bell + feed entry pointing at the story. Best-effort and
 * per-actor isolated so one stale participant never breaks publishing.
 */
export async function notifyStoryPublished(db: Db, news: { id: string; title: string; body: string; cityMemoryEventId: string }): Promise<number> {
  const event = await db.cityMemoryEvent.findUnique({ where: { id: news.cityMemoryEventId } });
  if (!event) return 0;
  const ids = actorIds(event);
  if (!ids.length) return 0;
  const players = await db.roundPlayer.findMany({ where: { id: { in: ids } }, select: { id: true } });
  const text = markdownToPlainText(news.body);
  const excerpt = text.length > 160 ? `${text.slice(0, 157).trimEnd()}...` : text;
  let notified = 0;
  for (const player of players) {
    try {
      await ActivityService.log(db, player.id, 'GAME_ANNOUNCEMENT', {
        newsId: news.id,
        title: news.title,
        excerpt,
        cityMemoryEventId: news.cityMemoryEventId,
      });
      notified += 1;
    } catch {
      continue;
    }
  }
  return notified;
}
