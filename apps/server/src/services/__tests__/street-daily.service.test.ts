import { describe, expect, it, vi } from 'vitest';
import { DRAFT_HELD_MS, generateDailyDrafts, notifyStoryPublished } from '../street-daily.service.js';

vi.mock('../activity.service.js', () => ({
  ActivityService: {
    log: vi.fn(async (db: any, roundPlayerId: string, type: string, payload: any) => {
      await db.playerActivity.create({ data: { roundPlayerId, type, payload } });
    }),
  },
}));

function makeDb(options: { events?: any[]; drafts?: any[]; players?: any[] } = {}) {
  const events = options.events ?? [];
  const drafts = options.drafts ?? [];
  const players = options.players ?? [];
  return {
    events,
    drafts,
    cityMemoryEvent: {
      findMany: vi.fn(async ({ where }: any) => events
        .filter((row) => !where?.roundId || row.roundId === where.roundId)
        .filter((row) => !where?.visibility || row.visibility === where.visibility)
        .sort((a, b) => a.happenedAt.getTime() - b.happenedAt.getTime())),
      findUnique: vi.fn(async ({ where }: any) => events.find((row) => row.id === where.id) ?? null),
    },
    gameNews: {
      findMany: vi.fn(async ({ where }: any) => drafts.filter((row) => !where?.cityMemoryEventId?.in
        || where.cityMemoryEventId.in.includes(row.cityMemoryEventId))),
      create: vi.fn(async ({ data }: any) => {
        const row = { id: `news-${drafts.length + 1}`, ...data };
        drafts.push(row);
        return row;
      }),
    },
    city: {
      findMany: vi.fn(async () => [{ id: 'city-1', name: 'Vice City' }]),
    },
    roundPlayer: {
      findMany: vi.fn(async ({ where }: any) => players.filter((row) => where.id.in.includes(row.id))),
    },
    playerActivity: {
      create: vi.fn(async ({ data }: any) => ({ id: `activity-${Math.random()}`, createdAt: new Date(), ...data })),
    },
    inAppNotification: { create: vi.fn(async ({ data }: any) => data) },
  } as any;
}

function takeover(id: string) {
  return {
    id,
    roundId: 'round-1',
    cityId: 'city-1',
    kind: 'takeover',
    visibility: 'public',
    actors: [],
    summary: { nextAllianceId: 'alliance-9', nextBlocksHeld: 3 },
    happenedAt: new Date('2026-10-02T00:00:00.000Z'),
  };
}

describe('2.0 street-daily', () => {
  it('drafts one held story per takeover, never twice', async () => {
    const db = makeDb({ events: [takeover('evt-1')] });
    expect(await generateDailyDrafts(db, { roundId: 'round-1' })).toBe(1);
    expect(await generateDailyDrafts(db, { roundId: 'round-1' })).toBe(0);
    expect(db.drafts).toHaveLength(1);
    expect(db.drafts[0].autoGenerated).toBe(true);
    expect(db.drafts[0].cityMemoryEventId).toBe('evt-1');
    expect(db.drafts[0].publishedAt.getTime()).toBeGreaterThan(Date.now() + DRAFT_HELD_MS - 60_000);
  });

  it('notifies participants when their story publishes', async () => {
    const db = makeDb({
      events: [{ ...takeover('evt-1'), kind: 'war_win', actors: ['player-a', 'gone-player'], summary: { reason: 'CONTROL', district: 'CASINO' } }],
      players: [{ id: 'player-a' }],
    });
    const notified = await notifyStoryPublished(db, { id: 'news-1', title: 'T', body: 'B', cityMemoryEventId: 'evt-1' });
    expect(notified).toBe(1);
    expect(db.playerActivity.create).toHaveBeenCalledTimes(1);
    expect(db.playerActivity.create.mock.calls[0][0].data.type).toBe('GAME_ANNOUNCEMENT');
  });
});
