"""Turn a high-resolution PNG of a Classic item into an 8-bit SVG master.

    python scripts/art/eight-bit.py in.png out.svg GRID_W GRID_H VIEW_W VIEW_H

The PNG is box-filtered down to a GRID_W x GRID_H sprite, alpha is cut at 50%,
the sprite gets its own 16-colour palette snapped to the 512-colour 8-bit grid,
lone speckles are cleaned up, and a one-pixel near-black outline is added round the silhouette. The SVG draws
each pixel as a square on the Classic viewBox, one path per colour, with crisp
edges so the render stays blocky.
"""
import sys
from PIL import Image

OUTLINE = (0x0A, 0x0A, 0x0A)
# 3 bits a channel: the 512-colour master palette of the 8-bit home consoles.
LEVELS = [0, 36, 73, 109, 146, 182, 219, 255]
COLOURS = 16


def snap(value):
    return min(LEVELS, key=lambda level: abs(level - value))


def palette_for(colours):
    """An adaptive palette of at most COLOURS entries, snapped to the 512-colour grid."""
    strip = Image.new('RGB', (len(colours), 1))
    strip.putdata(colours)
    quantised = strip.quantize(colors=COLOURS, method=Image.Quantize.MEDIANCUT)
    flat = quantised.getpalette()[: COLOURS * 3]
    mapping = {}
    for index, colour in zip(quantised.tobytes(), colours):
        r, g, b = flat[index * 3: index * 3 + 3]
        snapped = (snap(r), snap(g), snap(b))
        # Keep the darkest shades a step above the outline so dark items still read.
        if max(snapped) < 73:
            snapped = tuple(LEVELS[LEVELS.index(level) + 1] for level in snapped)
        mapping[colour] = snapped
    return mapping


def despeckle(grid):
    """Replace lone pixels whose four neighbours all agree on another colour."""
    height, width = len(grid), len(grid[0])
    out = [row[:] for row in grid]
    for y in range(1, height - 1):
        for x in range(1, width - 1):
            here = grid[y][x]
            if here is None:
                continue
            around = {grid[y - 1][x], grid[y + 1][x], grid[y][x - 1], grid[y][x + 1]}
            if len(around) == 1:
                (only,) = around
                if only is not None and only != here:
                    out[y][x] = only
    return out


def main():
    src, out, gw, gh, vw, vh = sys.argv[1], sys.argv[2], *map(int, sys.argv[3:7])
    image = Image.open(src).convert('RGBA').resize((gw, gh), Image.Resampling.BOX)
    px = image.load()
    grid = [[None] * gw for _ in range(gh)]
    for y in range(gh):
        for x in range(gw):
            r, g, b, a = px[x, y]
            if a >= 128:
                grid[y][x] = (r, g, b)
    opaque = [colour for row in grid for colour in row if colour is not None]
    mapping = palette_for(opaque)
    grid = despeckle([[mapping[colour] if colour is not None else None for colour in row] for row in grid])
    outlined = [row[:] for row in grid]
    for y in range(gh):
        for x in range(gw):
            if grid[y][x] is not None:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < gw and 0 <= ny < gh and grid[ny][nx] is not None:
                    outlined[y][x] = OUTLINE
                    break
    paths = {}
    for y in range(gh):
        x = 0
        while x < gw:
            colour = outlined[y][x]
            if colour is None:
                x += 1
                continue
            run = 1
            while x + run < gw and outlined[y][x + run] == colour:
                run += 1
            paths.setdefault(colour, []).append(f'M{x} {y}h{run}v1h-{run}z')
            x += run
    scale = vw / gw
    body = ''.join(
        f'<path fill="#{r:02x}{g:02x}{b:02x}" d="{"".join(d)}"/>'
        for (r, g, b), d in sorted(paths.items())
    )
    with open(out, 'w') as handle:
        handle.write(
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {vw} {vh}" shape-rendering="crispEdges">\n'
            f'  <!-- 8-Bit: generated by scripts/art/generate-eight-bit-art.mjs from the Classic art. -->\n'
            f'  <g transform="scale({scale:g})">{body}</g>\n'
            f'</svg>\n'
        )


if __name__ == '__main__':
    main()
