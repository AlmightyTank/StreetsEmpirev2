/**
 * Quest Recipe Unlocks C. Every recipe a round can cook, run through a day of cooking and
 * dealer sales in every city at three stages of an operation, then re-run with the
 * assumptions pushed both ways. The gate (see `recipeBalance`, `recipeResaleLoops` and
 * `ladderPacing` in the rules engine):
 *   - no recipe is a cash loop at Pip's counter, even with every bonus stacked;
 *   - every recipe is a real choice somewhere, and none is the best earner almost everywhere;
 *   - Crack alone pays at the start;
 *   - each rung of the recipe ladder cooks within a day of turns and pays more than it costs.
 *
 *   npm run qa:recipes -- [--ruleset classic-og-v1.8-m] [--output docs/RECIPE-BALANCE-1.8.0-M.md]
 */
import { writeFile } from 'node:fs/promises';
import { rulesets, type Ruleset } from '@streets/rulesets';
import {
  RECIPE_SCENARIOS, VIABLE_SHARE, MAX_WIN_SHARE, bestCookSupply, ladderPacing, productionFavorPercent, productRecipes, recipeBalance, recipeResale, type RecipeScenario,
} from '@streets/rules-engine';

const args = process.argv.slice(2);
const flag = (name: string) => { const at = args.indexOf(name); return at >= 0 ? args[at + 1] : undefined; };
const ruleset = rulesets[flag('--ruleset') ?? 'classic-og-v1.8-m'] as Ruleset | undefined;
if (!ruleset?.supplyNetwork?.dealers) throw new Error('That ruleset has no dealer crews to sell through.');

const money = (cents: number) => `${cents < 0 ? '-' : ''}$${Math.round(Math.abs(cents) / 100).toLocaleString('en-US')}`;
const exact = (cents: number) => `$${(cents / 100).toFixed(2)}`;
const city = (slug: string) => ruleset.cities?.[slug]?.name ?? slug;
const recipes = productRecipes(ruleset);
const supplier = (product: string) => {
  const offers = (ruleset.supplyNetwork?.suppliers ?? []).flatMap((row) => row.offers[product] ? [row.offers[product]!.unitCostCents] : []);
  return offers.length ? exact(Math.min(...offers)) : 'none';
};

const problems: string[] = [];
const balance = recipeBalance(ruleset);
problems.push(...balance.problems);
const ladder = ladderPacing(ruleset);
problems.push(...ladder.problems);

const lines = [
  `# Recipe balance — ${ruleset.meta.version}`,
  '',
  `Generated by \`npm run qa:recipes -- --ruleset ${ruleset.meta.id}\`. Expected values with no dice: happiness and variance average out.`,
  '',
  '## Recipes',
  '',
  'Cooking undercuts every supplier, but costs turns and thugs; past what the crew can cook, product still comes from orders.',
  '',
  '| Product | Per thug a turn | Ingredients | Heat a unit | Variance | Cheapest supplier | Pip\'s best home buyback | Cheapest unit to cook |',
  '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
];
const resale = new Map(recipeResale(ruleset).map((row) => [row.product, row]));
for (const recipe of recipes) {
  const row = resale.get(recipe.product);
  lines.push(`| ${recipe.name} | ${recipe.perThugPerTurn} | ${exact(recipe.ingredientCentsPerUnit)} | ${recipe.heatPerUnit} | ${recipe.variance} | ${supplier(recipe.product)} | ${row ? exact(row.bestBuybackCents) : '—'} | ${row ? exact(row.cheapestCookCents) : '—'} |`);
}
lines.push(
  '',
  'Pip\'s best home buyback stacks full standing, the best store-price racket and full market pressure; the cheapest unit takes the top workshop level and the Drug Lab. Every unit costs more to cook than Pip can pay for it at home. Pip\'s counters in other cities, reached on a run, pay their city\'s price: that is a trade with road risk, priced like any other run.',
  '',
  '## A day of cooking and dealing',
  '',
  'The crew cooks only what its dealers can sell, capped by its turns. Rookie dealers in an ordinary district; dealer wages are the same whatever they sell and are left out. Heat up to half the day\'s decay is free; past it, a unit is cooked only if its margin pays the bribe for its Heat at the player\'s net worth. Profit a day, best in bold; T marks a day the thugs\' turns ran out before the dealers did.',
  '',
);
for (const scenario of RECIPE_SCENARIOS) {
  lines.push(`### ${scenario.label}`, '', `| City | ${recipes.map((recipe) => recipe.name).join(' | ')} |`, `| --- | ${recipes.map(() => '---:').join(' | ')} |`);
  for (const row of balance.rows.filter((entry) => entry.scenario.key === scenario.key)) {
    const cells = recipes.map((recipe) => {
      const day = row.days.find((entry) => entry.product === recipe.product);
      if (!day) return '—';
      const text = `${money(day.profitCents)}${day.sold === day.cookCapacity && day.sold < day.dealerCapacity ? ' T' : ''}`;
      return day.product === row.best ? `**${text}**` : text;
    });
    lines.push(`| ${city(row.city)} | ${cells.join(' | ')} |`);
  }
  lines.push('');
}
lines.push(
  '## Who wins where',
  '',
  `| Product | Best earner | Within ${Math.round(VIABLE_SHARE * 100)}% of the best |`,
  '| --- | ---: | ---: |',
  ...recipes.map((recipe) => `| ${recipe.name} | ${balance.wins[recipe.product] ?? 0} of ${balance.rows.length} | ${balance.viable[recipe.product] ?? 0} of ${balance.rows.length} |`),
  '',
);

// The same gate with every assumption pushed both ways: the result must not hang on one guess.
const variations: Array<[string, (scenario: RecipeScenario) => RecipeScenario]> = [
  ['Half the turns', (s) => ({ ...s, turnsPerDay: s.turnsPerDay / 2 })],
  ['Twice the turns', (s) => ({ ...s, turnsPerDay: Math.min(576, s.turnsPerDay * 2) })],
  ['Twice the dealers', (s) => ({ ...s, dealers: s.dealers * 2 })],
  ['Half the thugs', (s) => ({ ...s, thugs: Math.max(1, Math.round(s.thugs / 2)) })],
  ['A tenth of the net worth', (s) => ({ ...s, netWorthCents: s.netWorthCents / 10 })],
  ['Ten times the net worth', (s) => ({ ...s, netWorthCents: s.netWorthCents * 10 })],
  ['No workshop', (s) => ({ ...s, workshopLevel: 0, drugLab: false })],
  // Slice E: a production favor and a crew supply policy both raise what the cooks make.
  [`Production favor (+${productionFavorPercent(ruleset)}% output)`, (s) => ({ ...s, favorOutputPercent: productionFavorPercent(ruleset) })],
  [`Cooks fed the best supply (x${bestCookSupply(ruleset)} output)`, (s) => ({ ...s, cookSupplyMultiplier: bestCookSupply(ruleset) })],
  ['Favor and fed cooks together', (s) => ({ ...s, favorOutputPercent: productionFavorPercent(ruleset), cookSupplyMultiplier: bestCookSupply(ruleset) })],
];
lines.push('## Sensitivity', '', `| Assumption | ${recipes.map((recipe) => recipe.name).join(' | ')} | Gate |`, `| --- | ${recipes.map(() => '---:').join(' | ')} | --- |`);
for (const [label, change] of variations) {
  const varied = recipeBalance(ruleset, RECIPE_SCENARIOS.map(change));
  lines.push(`| ${label} | ${recipes.map((recipe) => varied.wins[recipe.product] ?? 0).join(' | ')} | ${varied.problems.length ? 'fails' : 'passes'} |`);
  problems.push(...varied.problems.filter((problem) => !balance.problems.includes(problem)).map((problem) => `${label}: ${problem}`));
}
lines.push('', 'Each cell counts the situations where that product is the best earner.', '');

lines.push(
  '## The recipe ladder',
  '',
  'Each rung costed for a player at that stage. Cost is the cooking\'s ingredients plus what the Pip sales lose against what the units cost (cooked if the recipe is open, else the cheapest supplier or Pip\'s price).',
  '',
  '| Rung | Opens | Thugs | Turns of cooking | Cost | Cash paid |',
  '| --- | --- | ---: | ---: | ---: | ---: |',
  ...ladder.rungs.map((rung) => `| ${rung.title} | ${ruleset.products?.[rung.opens]?.name ?? rung.opens} | ${rung.thugs} | ${rung.cookTurns} | ${money(rung.costCents)} | ${money(rung.rewardCents)} |`),
  '',
  '## Gate',
  '',
  problems.length
    ? problems.map((problem) => `- ${problem}`).join('\n')
    : `Passed: no recipe is a cash loop at Pip's home counter, every recipe is within ${Math.round(VIABLE_SHARE * 100)}% of the best earner somewhere, no recipe is the best in more than ${Math.round(MAX_WIN_SHARE * 100)}% of situations (under every assumption above), Crack alone pays from the start in every city, and every rung of the ladder cooks within a day of turns and pays more than it costs.`,
  '',
);

const report = lines.join('\n');
const output = flag('--output');
if (output) await writeFile(output, report);
if (!args.includes('--quiet')) console.log(report);
if (problems.length) process.exitCode = 1;
